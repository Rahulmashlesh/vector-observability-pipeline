// pipelineNamespace is the namespace all Vector tiers run in.
const pipelineNamespace = "logging"

// agentConfigTemplate generates the Vector YAML config for the agent DaemonSet
// tier from a LogPipelineSpec.  The template uses only the validated enrichment
// VRL that was hand-tested in Stages 1-3; the only variable parts are the
// exclude path patterns (derived from spec.agent.excludeNamespaces) and the
// centralizer address (constant for a single-cluster deployment).
var agentConfigTemplate = template.Must(template.New("agent").Parse(`# Generated by logpipeline-operator — do not edit by hand.
# Source of truth: LogPipeline CR {{.Name}} ({{.Namespace}})
data_dir: /vector-data-dir

sources:
  kubernetes_logs:
    type: kubernetes_logs
    exclude_paths_glob_patterns:
      - /var/log/pods/logging_*/**
{{- range .ExcludePatterns}}
      - {{.}}
{{- end}}

transforms:
  enrich_metadata:
    type: remap
    inputs:
      - kubernetes_logs
    source: |
      .cluster_name = "endurance"

      .namespace       = to_string(.kubernetes.pod_namespace)       ?? "unknown"
      .pod_name        = to_string(.kubernetes.pod_name)            ?? "unknown"
      .node_name       = to_string(.kubernetes.pod_node_name)       ?? "unknown"
      .container       = to_string(.kubernetes.container_name)      ?? "unknown"
      .container_image = to_string(.kubernetes.container_image)     ?? "unknown"
      .stream          = to_string(.stream)                         ?? "stdout"

      pod_labels = .kubernetes.pod_labels

      .app = if is_string(pod_labels.app) {
        pod_labels.app
      } else if is_string(pod_labels."app.kubernetes.io/name") {
        pod_labels."app.kubernetes.io/name"
      } else if is_string(pod_labels."app.kubernetes.io/component") {
        pod_labels."app.kubernetes.io/component"
      } else if is_string(pod_labels."k8s-app") {
        pod_labels."k8s-app"
      } else if is_string(pod_labels."longhorn.io/component") {
        pod_labels."longhorn.io/component"
      } else if is_string(pod_labels."job-name") {
        replace(pod_labels."job-name", r'-\d+$', "")
      } else {
        abort
      }

sinks:
  centralizer:
    type: vector
    inputs:
      - enrich_metadata
    address: "vector-centralizer.logging.svc.cluster.local:6000"
    version: "2"
`))

// egressConfigTemplate generates the Vector YAML config for the egress
// Deployment tier.  The variable parts are the Loki endpoint and any
// extra labels declared in spec.egress.loki.
var egressConfigTemplate = template.Must(template.New("egress").Parse(`# Generated by logpipeline-operator — do not edit by hand.
# Source of truth: LogPipeline CR {{.Name}} ({{.Namespace}})
data_dir: /vector-data-dir

api:
  enabled: true
  address: "0.0.0.0:8686"

sources:
  centralizer_input:
    type: vector
    address: "0.0.0.0:6000"
    version: "2"

transforms:
  enrich_egress_metadata:
    type: remap
    inputs:
      - centralizer_input
    source: |
      .pipeline_tier = "egress"

      if !exists(.message) || is_null(.message) {
        .message = encode_json(.)
      }

      del(.kubernetes)
      del(.file)
      del(.source_type)

sinks:
  loki:
    type: loki
    inputs:
      - enrich_egress_metadata
    endpoint: "{{.LokiEndpoint}}"
    encoding:
      codec: json
    labels:
      cluster: "endurance"
      namespace: "{{ "{{" }} namespace {{ "}}" }}"
      pod: "{{ "{{" }} pod_name {{ "}}" }}"
      container: "{{ "{{" }} container {{ "}}" }}"
      node: "{{ "{{" }} node_name {{ "}}" }}"
      app: "{{ "{{" }} app {{ "}}" }}"
      stream: "{{ "{{" }} stream {{ "}}" }}"
      pipeline_tier: "egress"
{{- range .ExtraLabelLines}}
      {{.}}
{{- end}}
    batch:
      max_bytes: 1048576
      timeout_secs: 5
    request:
      retry_attempts: 5
      retry_initial_backoff_secs: 1
      retry_max_duration_secs: 30
    buffer:
      type: disk
      max_size: 536870912
      when_full: block
`))

// agentConfigData holds the template inputs for the agent config.
type agentConfigData struct {
	Name            string
	Namespace       string
	ExcludePatterns []string
}

// egressConfigData holds the template inputs for the egress config.
type egressConfigData struct {
	Name            string
	Namespace       string
	LokiEndpoint    string
	ExtraLabelLines []string
}

// buildAgentConfig renders the agent Vector YAML from the given spec.
// Always excludes the pipeline namespace (logging) plus any additional
// namespaces listed in spec.agent.excludeNamespaces.
func buildAgentConfig(pipeline *observabilityv1alpha1.LogPipeline) (string, error) {
	// Collect unique excluded namespaces; "logging" is baked into the
	// template as a literal so we skip it here to avoid duplication.
	seen := map[string]struct{}{"logging": {}}
	var patterns []string
	for _, ns := range pipeline.Spec.Agent.ExcludeNamespaces {
		if _, dup := seen[ns]; dup {
			continue
		}
		seen[ns] = struct{}{}
		patterns = append(patterns, fmt.Sprintf("/var/log/pods/%s_*/**", ns))
	}

	var buf bytes.Buffer
	if err := agentConfigTemplate.Execute(&buf, agentConfigData{
		Name:            pipeline.Name,
		Namespace:       pipeline.Namespace,
		ExcludePatterns: patterns,
	}); err != nil {
		return "", fmt.Errorf("rendering agent config template: %w", err)
	}
	return buf.String(), nil
}

// buildEgressConfig renders the egress Vector YAML from the given spec.
func buildEgressConfig(pipeline *observabilityv1alpha1.LogPipeline) (string, error) {
	// Sort extra labels for deterministic output (avoids spurious config
	// hash changes from map iteration order differences).
	keys := make([]string, 0, len(pipeline.Spec.Egress.Loki.ExtraLabels))
	for k := range pipeline.Spec.Egress.Loki.ExtraLabels {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var labelLines []string
	for _, k := range keys {
		// Sanitize: strip any quotes or newlines the user might have put in.
		v := strings.NewReplacer(`"`, "", "\n", "").Replace(pipeline.Spec.Egress.Loki.ExtraLabels[k])
		labelLines = append(labelLines, fmt.Sprintf(`%s: "%s"`, k, v))
	}

	var buf bytes.Buffer
	if err := egressConfigTemplate.Execute(&buf, egressConfigData{
		Name:            pipeline.Name,
		Namespace:       pipeline.Namespace,
		LokiEndpoint:    pipeline.Spec.Egress.Loki.Endpoint,
		ExtraLabelLines: labelLines,
	}); err != nil {
		return "", fmt.Errorf("rendering egress config template: %w", err)
	}
	return buf.String(), nil
}
